package dev.optimizer.android.features

import android.Manifest
import android.content.Context
import android.content.pm.PackageManager
import android.os.Build
import android.os.Environment
import androidx.core.content.ContextCompat
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.security.MessageDigest

data class CleanItem(val path: String, val size: Long, val kind: String, val note: String, val preselect: Boolean = false)
data class CleanScan(val items: List<CleanItem>, val note: String, val files: Int, val truncated: Boolean)
data class TrashEntry(val batch: String, val orig: String, val trashed: String, val size: Long, val ts: Long)

/**
 * Storage cleaner for shared storage (/sdcard). Nothing is ever deleted automatically: every item is shown with a checkbox, user media
 * (large files, duplicates, APKs) is never preselected, and ticked items are MOVED to AndroidOptimizer/Trash first so they can be restored.
 * Only the trash itself can be emptied (permanently).
 */
object Cleaner {
    fun root(): File = Environment.getExternalStorageDirectory()
    fun trashRoot(): File = File(root(), "AndroidOptimizer/Trash")

    fun hasAccess(ctx: Context): Boolean = when {
        Build.VERSION.SDK_INT >= 30 -> Environment.isExternalStorageManager()
        Build.VERSION.SDK_INT >= 23 -> ContextCompat.checkSelfPermission(ctx, Manifest.permission.WRITE_EXTERNAL_STORAGE) == PackageManager.PERMISSION_GRANTED
        else -> true
    }

    private fun size(f: File, budget: IntArray = intArrayOf(20000)): Long {
        if (f.isFile) return f.length()
        var s = 0L
        f.listFiles()?.forEach { if (budget[0]-- > 0) s += size(it, budget) }
        return s
    }

    fun scan(ctx: Context, progress: (String) -> Unit): CleanScan {
        val rootDir = root(); val trash = trashRoot()
        val started = System.currentTimeMillis(); var files = 0; var truncated = false
        val large = ArrayList<File>(); val apks = ArrayList<File>(); val thumbs = ArrayList<File>(); val empties = ArrayList<File>()
        val bySize = HashMap<Long, MutableList<File>>()

        fun walk(dir: File, depth: Int): Boolean { // returns true if the subtree has no files
            if (System.currentTimeMillis() - started > 90_000 || files > 400_000) { truncated = true; return false }
            if (dir == trash) return false
            val kids = runCatching { dir.listFiles() }.getOrNull() ?: return false
            if (kids.isEmpty()) return true
            if (dir.name.equals(".thumbnails", true) || (dir.name.equals("thumbnails", true) && dir.parentFile?.name in setOf("DCIM", "Pictures"))) { thumbs += dir; return false }
            var allEmpty = true
            for (k in kids) {
                if (k.isDirectory) {
                    if (depth == 0 && k.name == "Android") { allEmpty = false; continue } // other apps' private data: never touched
                    if (depth > 14) { allEmpty = false; continue }
                    if (runCatching { k.canonicalPath != k.absolutePath }.getOrDefault(true)) { allEmpty = false; continue } // symlink or odd mount: skip
                    val e = walk(k, depth + 1); if (e) empties += k else allEmpty = false
                } else {
                    allEmpty = false; files++
                    if (files % 2000 == 0) progress("Scanned $files files...")
                    val len = k.length()
                    if (len >= 100L shl 20) large += k
                    if (len >= 1L shl 20) bySize.getOrPut(len) { ArrayList() } += k
                    if (k.name.endsWith(".apk", true)) apks += k
                }
            }
            return allEmpty
        }
        walk(rootDir, 0)

        val items = ArrayList<CleanItem>()
        thumbs.forEach { items += CleanItem(it.path, size(it), "thumbs", "Thumbnail cache (regenerated by the gallery)", true) }
        // nested empty dirs: keep only top-most
        val emptySet = empties.map { it.path }.toSet()
        empties.filter { e -> emptySet.none { o -> o != e.path && e.path.startsWith("$o/") } }.take(300).forEach { items += CleanItem(it.path, 0, "empty", "Empty folder", true) }
        large.sortedByDescending { it.length() }.take(40).forEach { items += CleanItem(it.path, it.length(), "large", "Large file (${java.text.DateFormat.getDateInstance().format(java.util.Date(it.lastModified()))}) - your data, review carefully") }
        val pm = ctx.packageManager
        apks.sortedByDescending { it.length() }.take(60).forEach { f ->
            val info = runCatching { pm.getPackageArchiveInfo(f.path, 0) }.getOrNull()
            val inst = info?.let { runCatching { pm.getPackageInfo(it.packageName, 0) }.getOrNull() }
            val note = when {
                info == null -> "APK file (could not be parsed - possibly incomplete download)"
                inst == null -> "APK of ${info.packageName} ${info.versionName} (not installed)"
                else -> "APK of ${info.packageName} ${info.versionName}; installed version is ${inst.versionName} → likely safe to remove"
            }
            items += CleanItem(f.path, f.length(), "apk", note)
        }
        // duplicates: size -> quick fingerprint -> full SHA-256 (bounded)
        progress("Looking for duplicates...")
        var hashed = 0L; val dupStart = System.currentTimeMillis()
        val groups = bySize.values.filter { it.size >= 2 }.sortedByDescending { it.first().length() }
        outer@ for (g in groups) {
            val byHash = HashMap<String, MutableList<File>>()
            for (f in g) {
                if (hashed > (3L shl 30) || System.currentTimeMillis() - dupStart > 60_000) { truncated = true; break@outer }
                val h = runCatching { sha256(f) }.getOrNull() ?: continue
                hashed += f.length(); byHash.getOrPut(h) { ArrayList() } += f
            }
            for ((_, same) in byHash) if (same.size >= 2) {
                val keep = same.minWith(compareBy<File>({ it.lastModified() }, { it.path.length }))
                same.filter { it != keep }.forEach { items += CleanItem(it.path, it.length(), "dup", "Identical copy of ${keep.name} (${keep.parentFile?.name}); the original is kept") }
            }
        }
        val note = "Scanned $files files in ${rootDir.path}${if (truncated) " (stopped early: time/size budget reached, results are partial)" else ""}. Android/ (other apps' private data) is skipped."
        return CleanScan(items, note, files, truncated)
    }

    private fun sha256(f: File): String {
        val md = MessageDigest.getInstance("SHA-256"); val buf = ByteArray(1 shl 20)
        f.inputStream().use { i -> while (true) { val n = i.read(buf); if (n <= 0) break; md.update(buf, 0, n) } }
        return md.digest().joinToString("") { "%02x".format(it) }
    }

    private fun allowed(f: File): Boolean {
        val root = root().canonicalPath; val c = runCatching { f.canonicalPath }.getOrNull() ?: return false
        return c.startsWith("$root/") && !c.startsWith("$root/Android/") && !c.startsWith(trashRoot().canonicalPath)
    }

    private fun manifest() = File(trashRoot(), "manifest.json")
    fun trashList(): List<TrashEntry> = runCatching {
        val a = JSONArray(manifest().readText()); (0 until a.length()).map { val o = a.getJSONObject(it); TrashEntry(o.getString("batch"), o.getString("orig"), o.getString("trashed"), o.optLong("size"), o.optLong("ts")) }
    }.getOrDefault(emptyList())
    private fun saveManifest(l: List<TrashEntry>) { trashRoot().mkdirs(); manifest().writeText(JSONArray(l.map { JSONObject().put("batch", it.batch).put("orig", it.orig).put("trashed", it.trashed).put("size", it.size).put("ts", it.ts) }).toString()) }

    /** Moves the chosen items to the trash (empty folders are removed outright; they hold no data). Returns a human summary. */
    fun trash(items: List<CleanItem>): String {
        val batch = System.currentTimeMillis().toString(); val log = trashList().toMutableList()
        var moved = 0; var bytes = 0L; var removed = 0; val errs = mutableListOf<String>()
        items.forEachIndexed { idx, it ->
            val f = File(it.path)
            if (!f.exists()) return@forEachIndexed
            if (!allowed(f)) { errs += "${f.name}: outside shared storage - refused"; return@forEachIndexed }
            if (it.kind == "empty") { if (f.isDirectory && f.listFiles().isNullOrEmpty() && f.delete()) removed++ else errs += "${f.name}: no longer empty"; return@forEachIndexed }
            val dest = File(File(trashRoot(), batch).also { d -> d.mkdirs() }, "${idx}_${f.name}")
            val ok = f.renameTo(dest) || runCatching { if (f.isDirectory) f.copyRecursively(dest, true) && f.deleteRecursively() else { f.copyTo(dest, true); f.delete() } }.getOrDefault(false)
            if (ok) { moved++; bytes += it.size; log += TrashEntry(batch, f.path, dest.path, it.size, System.currentTimeMillis()) } else errs += "${f.name}: could not move"
        }
        saveManifest(log)
        return "Moved $moved item(s) (${bytes / 1048576} MB) to ${trashRoot().path}, removed $removed empty folder(s)." + if (errs.isNotEmpty()) "\n" + errs.joinToString("\n") else ""
    }

    fun restore(entries: List<TrashEntry>): String {
        val log = trashList().toMutableList(); var n = 0; val errs = mutableListOf<String>()
        for (e in entries) {
            val src = File(e.trashed); val dst = File(e.orig)
            if (!src.exists()) { log.remove(e); continue }
            if (dst.exists()) { errs += "${dst.name}: original location is occupied"; continue }
            dst.parentFile?.mkdirs()
            val ok = src.renameTo(dst) || runCatching { if (src.isDirectory) src.copyRecursively(dst) && src.deleteRecursively() else { src.copyTo(dst); src.delete() } }.getOrDefault(false)
            if (ok) { n++; log.remove(e) } else errs += "${dst.name}: could not restore"
        }
        saveManifest(log)
        return "Restored $n item(s)." + if (errs.isNotEmpty()) "\n" + errs.joinToString("\n") else ""
    }

    fun trashSize(): Long = trashList().sumOf { it.size }
    fun emptyTrash(): String { val n = trashList().size; trashRoot().deleteRecursively(); return "Permanently deleted $n item(s) from the trash." }

    fun clearOwnCache(ctx: Context): Long { val b = size(ctx.cacheDir); ctx.cacheDir.listFiles()?.forEach { it.deleteRecursively() }; return b }
}
